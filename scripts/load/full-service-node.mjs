import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { performance } from 'node:perf_hooks';

const baseUrl = process.env.BASE_URL || 'http://localhost:8080';
const users = Number(process.env.USERS || 100);
const durationSeconds = Number(process.env.DURATION_SECONDS || 60);
const timeoutMs = Number(process.env.REQUEST_TIMEOUT_MS || 10000);
const tokenFile = process.env.TOKENS_FILE;
const outputDirectory = resolve(process.env.RESULT_DIR || 'target/load-test-results/full-service');

if (!tokenFile) throw new Error('TOKENS_FILE is required.');
const tokenData = JSON.parse(readFileSync(resolve(tokenFile), 'utf8'));
if (!Array.isArray(tokenData.tokens) || tokenData.tokens.length < users) {
  throw new Error(`Token file has ${tokenData.tokens?.length || 0} entries, but ${users} are required.`);
}

const clients = tokenData.tokens.slice(0, users).map((entry, index) => ({
  index,
  token: typeof entry === 'string' ? entry : entry.token,
  guardianSubject: typeof entry === 'string' ? null : entry.guardianSubject,
  userId: null,
  cardId: null,
}));
if (clients.some((client) => !client.guardianSubject)) {
  throw new Error('Full-service test requires token metadata generated by the current prepare script.');
}

const records = new Map();
const resources = { peakCpu: 0, peakHeapBytes: 0, peakDbConnections: 0, peakSse: 0, samples: 0, samplingErrors: 0 };

function recordFor(name) {
  if (!records.has(name)) records.set(name, { attempts: 0, errors: 0, latencies: [], statuses: {} });
  return records.get(name);
}

function sleep(ms) {
  return new Promise((done) => setTimeout(done, Math.max(0, ms)));
}

function deviceHeaders(client) {
  return { Authorization: `Bearer ${client.token}`, 'Content-Type': 'application/json' };
}

function guardianHeaders(client) {
  return { 'X-Load-Test-Subject': client.guardianSubject, 'Content-Type': 'application/json' };
}

async function rawRequest(path, options) {
  const response = await fetch(`${baseUrl}${path}`, { ...options, signal: AbortSignal.timeout(timeoutMs) });
  const text = await response.text();
  let json = null;
  if (text) {
    try { json = JSON.parse(text); } catch { json = null; }
  }
  return { response, json };
}

async function measuredRequest(name, client, definition) {
  const record = recordFor(name);
  record.attempts += 1;
  const started = performance.now();
  try {
    const { response } = await rawRequest(definition.path(client), {
      method: definition.method || 'GET',
      headers: definition.guardian ? guardianHeaders(client) : deviceHeaders(client),
      body: definition.body ? JSON.stringify(definition.body(client)) : undefined,
    });
    record.latencies.push(performance.now() - started);
    record.statuses[response.status] = (record.statuses[response.status] || 0) + 1;
    if (!response.ok) record.errors += 1;
  } catch (error) {
    record.errors += 1;
    const key = error?.name || 'transport-error';
    record.statuses[key] = (record.statuses[key] || 0) + 1;
  }
}

async function prepareClient(client) {
  const board = await rawRequest('/api/v1/device/board', { headers: deviceHeaders(client) });
  if (!board.response.ok || !board.json?.data?.cards?.[0]?.id) {
    throw new Error(`Device board preparation failed for client ${client.index}: ${board.response.status}`);
  }
  client.cardId = board.json.data.cards[0].id;

  const location = await rawRequest('/api/v1/device/locations', {
    method: 'POST',
    headers: deviceHeaders(client),
    body: JSON.stringify({ latitude: 37.6026, longitude: 126.9553, accuracyMeters: 15 }),
  });
  if (!location.response.ok) {
    throw new Error(`Location preparation failed for client ${client.index}: ${location.response.status}`);
  }

  const usersResponse = await rawRequest('/api/v1/me/aac-users', { headers: guardianHeaders(client) });
  if (!usersResponse.response.ok || !usersResponse.json?.data?.[0]?.id) {
    throw new Error(`Guardian preparation failed for client ${client.index}: ${usersResponse.response.status}`);
  }
  client.userId = usersResponse.json.data[0].id;
}

for (let offset = 0; offset < clients.length; offset += 25) {
  await Promise.all(clients.slice(offset, offset + 25).map(prepareClient));
}

