async function runPeriodic(client, definition, startAt, endAt) {
  const stagger = (((client.index + 1) * 2654435761
    + definition.multiplier * 1013904223) >>> 0) % definition.intervalMs;
  let nextAt = startAt + stagger;
  await sleep(Math.min(nextAt, endAt) - Date.now());
  while (Date.now() < endAt) {
    await measuredRequest(definition.name, client, definition);
    nextAt += definition.intervalMs;
    await sleep(Math.min(nextAt, endAt) - Date.now());
  }
}

function metricValues(text, metricName, predicate = () => true) {
  const values = [];
  for (const line of text.split('\n')) {
    if (!line.startsWith(metricName) || line.startsWith('#')) continue;
    const separator = line.lastIndexOf(' ');
    if (separator < 0 || !predicate(line.slice(0, separator))) continue;
    const value = Number(line.slice(separator + 1));
    if (Number.isFinite(value)) values.push(value);
  }
  return values;
}

async function sampleResources() {
  try {
    const response = await fetch(`${baseUrl}/actuator/prometheus`, { signal: AbortSignal.timeout(timeoutMs) });
    if (!response.ok) throw new Error(`metrics-${response.status}`);
    const text = await response.text();
    const cpu = metricValues(text, 'process_cpu_usage')[0] || 0;
    const heap = metricValues(text, 'jvm_memory_used_bytes', (labels) => labels.includes('area="heap"')).reduce((sum, value) => sum + value, 0);
    const db = metricValues(text, 'hikaricp_connections_active').reduce((sum, value) => sum + value, 0);
    const sse = metricValues(text, 'malmoa_sse_connections_active')[0] || 0;
    resources.peakCpu = Math.max(resources.peakCpu, cpu);
    resources.peakHeapBytes = Math.max(resources.peakHeapBytes, heap);
    resources.peakDbConnections = Math.max(resources.peakDbConnections, db);
    resources.peakSse = Math.max(resources.peakSse, sse);
    resources.samples += 1;
  } catch { resources.samplingErrors += 1; }
}

function percentile(values, ratio) {
  if (!values.length) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.ceil(sorted.length * ratio) - 1)];
}

const startAt = Date.now() + 2000;
const endAt = startAt + durationSeconds * 1000;
await sampleResources();
const metricsTimer = setInterval(sampleResources, 1000);
const jobs = [];
for (const client of clients) {
  for (const definition of definitions) {
    if (!definition.selector || definition.selector(client)) jobs.push(runPeriodic(client, definition, startAt, endAt));
  }
}
await Promise.all(jobs);
clearInterval(metricsTimer);
await sampleResources();

const endpoints = {};
const allLatencies = [];
let attempts = 0;
let errors = 0;
for (const [name, record] of records.entries()) {
  attempts += record.attempts;
  errors += record.errors;
  allLatencies.push(...record.latencies);
  endpoints[name] = {
    attempts: record.attempts,
    errors: record.errors,
    p95Ms: percentile(record.latencies, 0.95),
    p99Ms: percentile(record.latencies, 0.99),
    maxMs: percentile(record.latencies, 1),
    statuses: record.statuses,
  };
}

const result = {
  executedAt: new Date().toISOString(), runId: tokenData.runId,
  environment: 'Node mixed workload -> Spring Boot -> PostgreSQL 16', users, durationSeconds,
  attempts, errors, errorRate: attempts ? errors / attempts : 0, rps: attempts / durationSeconds,
  p50Ms: percentile(allLatencies, 0.50), p95Ms: percentile(allLatencies, 0.95),
  p99Ms: percentile(allLatencies, 0.99), maxMs: percentile(allLatencies, 1), resources, endpoints,
};

mkdirSync(outputDirectory, { recursive: true });
const stamp = new Date().toISOString().replace(/[:.]/g, '-');
const path = resolve(outputDirectory, `full-${users}users-${durationSeconds}s-${stamp}.json`);
writeFileSync(path, JSON.stringify(result, null, 2), 'utf8');
console.log(JSON.stringify({ ...result, path }, null, 2));
